"""
AEI — Pipeline Demo Script
============================
Demonstrates the full Milestone 1 data pipeline on a SYNTHETIC fixture.

Run from the AEI/ directory:
    python scripts/demo_pipeline.py

OUTPUT DISCLAIMER
-----------------
All data used here is SYNTHETIC (generated by tests/fixtures/make_synthetic_fixture.py).
Metrics printed here are NOT real-world accuracy scores.
They exist only to demonstrate that the pipeline runs without errors.
"""

from __future__ import annotations

import sys
import time
from pathlib import Path

# Make src importable
_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(_ROOT / "src"))

import pandas as pd

from data_pipeline.cleaning import (
    apply_cleaning_pipeline,
    clean_training_data,
    duplicate_report,
    missing_value_report,
    numeric_summary,
)
from data_pipeline.feature_engineering import (
    apply_feature_pipeline,
    build_model_feature_matrix,
    feature_column_report,
    fit_feature_pipeline,
)
from data_pipeline.ingestion import load_csv, validate_dataframe
from integration.schemas import (
    HazardPredictionBatch,
    HazardPredictionRecord,
    PredictionStatus,
    RiskOutputBatch,
    RiskOutputRecord,
    RiskStatus,
    RiskCategory,
    make_valid_prediction,
    make_valid_risk,
)
from tests.fixtures.make_synthetic_fixture import (
    make_clean_fixture,
    make_dirty_fixture,
    save_fixtures,
    SIMULATED_DIR,
)


def section(title: str) -> None:
    print()
    print("=" * 60)
    print(f"  {title}")
    print("=" * 60)


def main() -> None:
    print()
    print("AEI — Milestone 1 Pipeline Demo")
    print("DATA SOURCE: SYNTHETIC (not real observations)")
    print("These results do NOT validate real-world model accuracy.")

    # ------------------------------------------------------------------
    # 0. Generate and save synthetic fixtures
    # ------------------------------------------------------------------
    section("0. Generate SYNTHETIC fixtures")
    save_fixtures()

    # ------------------------------------------------------------------
    # 1. Ingestion
    # ------------------------------------------------------------------
    section("1. Ingestion — load clean fixture via load_csv")

    t0 = time.perf_counter()
    clean_path = SIMULATED_DIR / "synthetic_clean_200.csv"
    df_raw = load_csv(clean_path, data_source_label="SYNTHETIC",
                      schema_name="kaggle_s4e5")
    load_time = time.perf_counter() - t0

    print(f"  Loaded {len(df_raw)} rows × {len(df_raw.columns)} columns")
    print(f"  Data source label : {df_raw.attrs['_data_source']}")
    print(f"  Schema validated  : kaggle_s4e5")
    print(f"  Load time         : {load_time*1000:.2f} ms")
    print()
    print("  First 3 rows (feature columns only):")
    feat_cols = [c for c in df_raw.columns
                 if c not in ("id", "zone_id", "event_id", "FloodProbability")]
    print(df_raw[feat_cols[:5]].head(3).to_string(index=False))

    # ------------------------------------------------------------------
    # 2. Dirty fixture — data-quality report
    # ------------------------------------------------------------------
    section("2. Data-quality diagnostics on DIRTY fixture")

    dirty_path = SIMULATED_DIR / "synthetic_dirty_50.csv"
    df_dirty = load_csv(dirty_path, data_source_label="SYNTHETIC")

    print("  Missing value report:")
    mvr = missing_value_report(df_dirty)
    if len(mvr) == 0:
        print("  (no missing values)")
    else:
        print(mvr.to_string(index=False))

    print()
    print("  Duplicate report:", duplicate_report(df_dirty))

    # ------------------------------------------------------------------
    # 3. Cleaning
    # ------------------------------------------------------------------
    section("3. Cleaning — fit on training split, apply to test split")

    # Split 80/20 (index-based — no temporal structure in synthetic data)
    split = int(0.8 * len(df_raw))
    df_train_raw = df_raw.iloc[:split].copy()
    df_test_raw  = df_raw.iloc[split:].copy()

    from data_pipeline.cleaning import fit_cleaning_pipeline

    bounds = {col: (0.0, 10.0) for col in feat_cols}
    cleaning_stats = fit_cleaning_pipeline(
        df_train_raw,
        column_bounds=bounds,
    )
    df_train_clean = apply_cleaning_pipeline(
        df_train_raw, cleaning_stats,
        drop_target_nulls=True, target_column="FloodProbability",
    )
    df_test_clean = apply_cleaning_pipeline(
        df_test_raw, cleaning_stats,
        drop_target_nulls=False, target_column="FloodProbability",
    )

    print(f"  Training rows after cleaning : {len(df_train_clean)}")
    print(f"  Test rows after cleaning     : {len(df_test_clean)}")
    print()
    print("  Training numeric summary (mean ± std for first 3 features):")
    summary = numeric_summary(df_train_clean)
    print(summary[["mean", "std"]].head(3).to_string())

    # ------------------------------------------------------------------
    # 4. Feature engineering
    # ------------------------------------------------------------------
    section("4. Feature engineering")

    t0 = time.perf_counter()
    fe_stats = fit_feature_pipeline(df_train_clean)
    df_train_eng = apply_feature_pipeline(df_train_clean, fe_stats)
    df_test_eng  = apply_feature_pipeline(df_test_clean,  fe_stats)
    fe_time = time.perf_counter() - t0

    print(f"  Engineering time (train+test) : {fe_time*1000:.2f} ms")
    print()
    print("  Engineered column report (first 5):")
    report = feature_column_report(df_train_eng)
    print(report.head(5).to_string(index=False))

    # ------------------------------------------------------------------
    # 5. Build feature matrix
    # ------------------------------------------------------------------
    section("5. Build feature matrix X / target y")

    X_train, y_train = build_model_feature_matrix(
        df_train_eng, target_col="FloodProbability"
    )
    X_test, y_test = build_model_feature_matrix(
        df_test_eng, target_col="FloodProbability"
    )

    print(f"  X_train : {X_train.shape}   y_train nulls: {y_train.isna().sum()}")
    print(f"  X_test  : {X_test.shape}    y_test nulls: {y_test.isna().sum()}")
    print(f"  Feature columns ({len(X_train.columns)}):")
    for col in X_train.columns[:6]:
        print(f"    {col}")
    if len(X_train.columns) > 6:
        print(f"    ... (+{len(X_train.columns)-6} more)")

    # ------------------------------------------------------------------
    # 6. Integration schemas
    # ------------------------------------------------------------------
    section("6. Integration schema — build sample GIS output")

    predictions = []
    for _, row in df_test_eng.head(5).iterrows():
        zone_id = str(row.get("zone_id", f"ZONE_{int(row.name)+1:04d}"))
        val = float(row.get("composite_risk_norm", 0.5))
        predictions.append(HazardPredictionRecord(
            zone_id=zone_id,
            prediction_time="2024-06-01T12:00:00Z",
            target_name="FloodProbability",
            predicted_value=round(val, 4),
            target_unit="dimensionless_0_to_1",
            forecast_horizon="static_snapshot",
            model_version="0.1.0",
            data_timestamp="2024-06-01T06:00:00Z",
            prediction_status=PredictionStatus.OK,
        ))

    batch = HazardPredictionBatch(
        records=predictions,
        generated_at="2024-06-01T12:00:00Z",
        scenario_id="DEMO_SCENARIO_001",
    )

    print(f"  Hazard prediction batch: {len(batch.records)} records")
    for rec in batch.to_csv_records()[:3]:
        print(f"    zone={rec['zone_id']:12s}  val={rec['predicted_value']:.4f}"
              f"  status={rec['prediction_status']}")

    # Risk batch
    risk_records = []
    for pred in predictions:
        score = pred.predicted_value
        cat = (RiskCategory.CRITICAL if score >= 0.75
               else RiskCategory.HIGH if score >= 0.5
               else RiskCategory.MODERATE if score >= 0.25
               else RiskCategory.LOW)
        risk_records.append(RiskOutputRecord(
            zone_id=pred.zone_id,
            risk_score=score,
            risk_category=cat,
            data_freshness="PT6H",
            risk_status=RiskStatus.OK,
            contributing_factors=["composite_risk_norm"],
        ))

    risk_batch = RiskOutputBatch(
        records=risk_records,
        generated_at="2024-06-01T12:00:00Z",
        scenario_id="DEMO_SCENARIO_001",
    )
    print()
    print(f"  Risk output batch: {len(risk_batch.records)} records")
    for rec in risk_batch.to_csv_records()[:3]:
        print(f"    zone={rec['zone_id']:12s}  score={rec['risk_score']:.4f}"
              f"  category={rec['risk_category']}")

    # ------------------------------------------------------------------
    # Summary
    # ------------------------------------------------------------------
    section("Demo complete — summary")
    print("  Pipeline stages executed : Ingestion → Cleaning → Engineering → Schemas")
    print("  Data provenance          : SYNTHETIC (not real observations)")
    print("  No model was trained     : that is Milestone 2")
    print()
    print("  Unresolved decisions:")
    print("    1. Real dataset not yet downloaded (IMD / Kaggle S4E5).")
    print("    2. Temporal split strategy requires a real event timeline.")
    print("    3. Integration contract to be reviewed with GIS teammate.")
    print("    4. Risk-score thresholds are placeholders — need calibration.")


if __name__ == "__main__":
    main()
